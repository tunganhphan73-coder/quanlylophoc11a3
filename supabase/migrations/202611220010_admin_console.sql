-- Admin-only teacher directory and app error reports.
-- This migration is additive: it does not modify or delete existing records.

create table if not exists public.app_error_reports (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  actor_role text,
  error_digest text not null default '',
  message text not null default '',
  route text not null default '',
  created_at timestamptz not null default now()
);

alter table public.app_error_reports enable row level security;
revoke all on public.app_error_reports from anon, authenticated;
grant select on public.app_error_reports to authenticated;
grant all on public.app_error_reports to service_role;
grant usage, select on sequence public.app_error_reports_id_seq to service_role;

create table if not exists public.app_error_report_rate_limits (
  user_id uuid primary key references auth.users(id) on delete cascade,
  window_started_at timestamptz not null default now(),
  request_count integer not null default 0
);
alter table public.app_error_report_rate_limits enable row level security;
revoke all on public.app_error_report_rate_limits from anon, authenticated;
grant all on public.app_error_report_rate_limits to service_role;

create or replace function public.consume_app_error_report_rate_limit(p_user_id uuid)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_count integer;
begin
  insert into public.app_error_report_rate_limits (user_id, window_started_at, request_count)
  values (p_user_id, now(), 1)
  on conflict (user_id) do update
    set window_started_at = case
          when app_error_report_rate_limits.window_started_at <= now() - interval '1 minute' then now()
          else app_error_report_rate_limits.window_started_at
        end,
        request_count = case
          when app_error_report_rate_limits.window_started_at <= now() - interval '1 minute' then 1
          else app_error_report_rate_limits.request_count + 1
        end
  returning request_count into v_count;
  return v_count <= 10;
end;
$$;
revoke all on function public.consume_app_error_report_rate_limit(uuid) from public, anon, authenticated;
grant execute on function public.consume_app_error_report_rate_limit(uuid) to service_role;

do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'app_error_reports'
      and policyname = 'Admins can view app error reports'
  ) then
    create policy "Admins can view app error reports"
      on public.app_error_reports for select to authenticated
      using (
        exists (
          select 1 from public.profiles p
          where p.id = auth.uid() and p.access_role = 'admin'
        )
      );
  end if;
end
$$;

create index if not exists idx_app_error_reports_created_at
  on public.app_error_reports (created_at desc, id desc);
-- Supports admin's newest-first error feed without scanning the full log table.
create index if not exists idx_app_error_reports_digest_created_at
  on public.app_error_reports (error_digest, created_at desc)
  where error_digest <> '';

comment on table public.app_error_reports is
  'Sanitized application error telemetry; writes are server-only and reads are admin-only.';
